analyzer = SentimentIntensityAnalyzer()

def compute_sentiment_vader(review):
    """
    Computes the sentiment of a given review using the VADER sentiment analyzer.

    Args:
        review (str): The text of the review to analyze.

    Returns:
        str: The sentiment of the review, which can be "positive", "negative", or "neutral".
    """
    score = analyzer.polarity_scores(review)["compound"]
    if score >= 0.05:
        return "positive"
    elif score <= -0.05:
        return "negative"
    else:
        return "neutral"

def compute_sentiments(reviews):
    """
    Computes the sentiment for a list of reviews.

    Args:
        reviews (list of str): A list of review texts to analyze.

    Returns:
        list of str: A list of sentiments corresponding to each review.
    """
    return [compute_sentiment_vader(r) for r in reviews]

def compute_sentiment_score(sentiments):
    """
    Computes the sentiment distribution as a percentage for a list of sentiments.

    Args:
        sentiments (list of str): A list of sentiments ("positive", "negative", "neutral").

    Returns:
        dict: A dictionary with the percentage distribution of each sentiment.
    """
    total = len(sentiments)
    counts = {"positive": 0, "negative": 0, "neutral": 0}
    for s in sentiments:
        counts[s] += 1
    return {k: round(v / total, 2) for k, v in counts.items()}
