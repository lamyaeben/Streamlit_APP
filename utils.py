def get_cached_or_fresh_data(search_term, search_function, cache_dir="cache", **kwargs):
    """
    Retrieves data either from a local cache or by performing an online search.
    This function checks if the requested data is already cached in a JSON file. 
    If the cache exists, it loads the data from the file. Otherwise, it performs 
    an online search using the provided search function, saves the result to the 
    cache, and returns the data.
    Args:
        search_term (str): The term to search for, used to generate the cache filename.
        search_function (callable): A function that performs the search and returns 
            the data as a DataFrame or similar structure.
        cache_dir (str, optional): The directory where cached files are stored. 
            Defaults to "cache".
        **kwargs: Additional keyword arguments to pass to the search function.
    Returns:
        pd.DataFrame: A DataFrame containing the retrieved data, either from the 
        cache or from the online search.
    Notes:
        - The cache filename is generated by replacing spaces in the search term 
          with underscores and appending the search function's name.
        - The data is cached in JSON format with UTF-8 encoding.
        - If the cache directory does not exist, it will be created automatically.
   
    """
    if not os.path.exists(cache_dir):
        os.makedirs(cache_dir)
    safe_term = search_term.replace(" ", "_").lower()
    json_path = os.path.join(cache_dir, f"{safe_term}{search_function.__name__}.json")

    if os.path.exists(json_path):
        print(f"🔁 Chargement du cache pour '{search_term}' ({search_function.__name__})")
        with open(json_path, "r", encoding="utf-8") as f:
            return pd.DataFrame(json.load(f))
    else:
        print(f"🆕 Recherche en ligne pour '{search_term}' ({search_function.__name__})")
        df = search_function(search_term, **kwargs)
        df.to_json(json_path, orient="records", indent=4, force_ascii=False)
        return pd.DataFrame(df)


