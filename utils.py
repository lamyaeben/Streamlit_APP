def stars(button):
    try:
        filled = 0
        half = 0
        stars = button.find_elements(By.TAG_NAME, 'label')
        for star in stars:
            try:
                etoile = star.find_element(By.TAG_NAME, 'svg')
                outer_html = etoile.get_attribute("outerHTML") or ""
                if ('fill-[#f5a623]' in outer_html or 'fill: #f5a623' in outer_html) and 'clip-path' not in outer_html:
                    filled += 1
                if '<clipPath id="StartHalfFilled_svg_a">' in outer_html or 'clip-path="url(#StartHalfFilled_svg_a)"' in outer_html:
                    half += 1
            except:
                continue
        return filled + (half * 0.5)
    except:
        return None


