def search_producthunt_no_cache(search_term: str):
    """
    Searches Product Hunt for products matching the given search term using Selenium and returns the results as a pandas DataFrame.
    This function uses a web scraper to navigate the Product Hunt website, extract product details, and compile them into a structured format. 
    It does not use caching, so each call will perform a fresh search.
    Args:
        search_term (str): The search term to query on Product Hunt.
    Returns:
        pandas.DataFrame: A DataFrame containing the following columns for each product:
            - title (str): The title of the product.
            - tagline (str): The tagline or short description of the product.
            - review (str): The review or feedback associated with the product.
            - rating (float or None): The star rating of the product, if available.
            - followers (str): The number of followers for the product, if available.
            - more_details (str): Additional details about the product.
    Notes:
        - This function requires the Selenium library and a compatible Chrome WebDriver to be installed.
        - The function may take a significant amount of time to execute depending on the number of products and network latency.
        - Ensure that the ChromeDriver version matches your installed Chrome browser version.
        - The function includes a series of try-except blocks to handle missing elements gracefully.
        - The function uses explicit waits and sleep calls to ensure elements are loaded before interacting with them.
    Raises:
        Exception: If there are issues with the web scraping process, such as element not found or navigation errors.
    Example:
        >>> df = search_producthunt_no_cache("AI tools")
        >>> print(df.head())
    """
    # Configurer Selenium
    options = webdriver.ChromeOptions()
    options.add_argument("--headless")  # décommente pour exécuter sans interface
    service = Service(ChromeDriverManager().install())
    driver = webdriver.Chrome(service=service, options=options)

    url = f"https://www.producthunt.com/search?q={search_term.replace(' ', '%20')}"
    driver.get(url)

    wait = WebDriverWait(driver, 10)
    wait.until(EC.presence_of_element_located((By.CSS_SELECTOR, 'main div.px-8.pb-8.sm\\:py-8')))
    time.sleep(10)

    results = []
    product_buttons = driver.find_elements(By.CSS_SELECTOR, 'main div.px-8.pb-8.sm\\:py-8 > div > button')

    for i in range(len(product_buttons)):
        try:
            product_buttons = driver.find_elements(By.CSS_SELECTOR, 'main div.px-8.pb-8.sm\\:py-8 > div > button')
            button = product_buttons[i]
            driver.execute_script("arguments[0].click();", button)
            time.sleep(8)

            try:
                followers = driver.find_element(By.CSS_SELECTOR, '#root-container > div.pt-header > div > main > section.flex.flex-col.gap-4.sm\\:flex-row.sm\\:items-center > div:nth-child(2) > span > p').text
            except:
                followers = "NONE"

            try:
                title = driver.find_element(By.CSS_SELECTOR, 'section.flex.flex-col.gap-4.sm\\:flex-row.sm\\:items-center > div:nth-child(2) > h1').text
            except:
                title = "NONE"

            try:
                tagline = driver.find_element(By.CSS_SELECTOR, '#root-container > div.pt-header > div > main > section.flex.flex-col.gap-4.sm\\:flex-row.sm\\:items-center > div:nth-child(2) > h2').text
            except:
                tagline = "NONE"

            try:
                review = driver.find_element(By.CSS_SELECTOR, 'section.flex.flex-col.gap-4.sm\\:flex-row.sm\\:items-center > div:nth-child(2) > span > a:nth-child(3)').text
            except:
                review = "NONE"

            try:
                stars_container = driver.find_element(By.CSS_SELECTOR, 'section.flex.flex-col.gap-4.sm\\:flex-row.sm\\:items-center > div:nth-child(2) > span > div.flex.flex-row')
                rating = stars(stars_container)
            except:
                rating = None

            try:
                more_details = driver.find_element(By.CSS_SELECTOR, 'section:nth-child(3) > div').text
            except:
                more_details = "NONE"

            results.append({
                "title": title,
                "tagline": tagline,
                "review": review,
                "rating": rating,
                "followers": followers,
                "more_details": more_details
            })

            driver.back()
            time.sleep(10)
        except Exception as e:
            print(f"Erreur produit {i}: {e}")
            driver.back()
            time.sleep(10)

    driver.quit()
    return pd.DataFrame(results)


