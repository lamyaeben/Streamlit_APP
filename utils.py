def update_search_history(new_term):
    """
    Updates the search history stored in the Streamlit session state.

    This function ensures that the search history is maintained as a list of unique
    search terms, with the most recent term added to the beginning of the list.
    The history is limited to the 10 most recent terms.

    Args:
        new_term (str): The new search term to add to the history.

    Notes:
        - If the session state does not already contain a search history, it initializes it.
        - Duplicate terms are not added to the history.
    """
  
    if "search_history" not in st.session_state:
        st.session_state.search_history = []
    if new_term and new_term not in st.session_state.search_history:
        st.session_state.search_history.insert(0, new_term)
        st.session_state.search_history = st.session_state.search_history[:10] # Limit to 10 items

